function generateId() {
  return 'c' + Math.random().toString(36).substring(2, 15) + Math.random().toString(36).substring(2, 15);
}

async function main() {
  console.log("🌱 Starting seed...");

  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) {
    throw new Error("DATABASE_URL not found");
  }

  const sql = neon(connectionString);

  // Clear existing vehicles
  await sql`DELETE FROM "h12"."Vehicle"`;
  console.log("🗑️  Cleared existing vehicles");

  // Insert all vehicles
  const allVehicles = [...cars, ...motos];

  for (const v of allVehicles) {
    const id = generateId();
    const now = new Date().toISOString();
    await sql`
      INSERT INTO "h12"."Vehicle" (
        id, type, name, category, price, period, image, description,
        features, fuel, seats, transmission, year, power, available, featured,
        "createdAt", "updatedAt"
      ) VALUES (
        ${id}, ${v.type}::"h12"."VehicleType", ${v.name}, ${v.category}, ${v.price}, ${v.period}, ${v.image}, ${v.description},
        ${v.features}, ${v.fuel}, ${v.seats}, ${v.transmission}, ${v.year}, ${v.power}, true, ${v.featured},
        ${now}::timestamp, ${now}::timestamp
      )
    `;
  }

  console.log(`✅ Inserted ${cars.length} cars`);
  console.log(`✅ Inserted ${motos.length} motos`);
  console.log("🎉 Seed completed!");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  });
